// Контент лендингов конкретных обучений: /courses/[courseSlug].
// Курсы живут в Firestore, но продающий текст — редакторская работа, поэтому он
// лежит здесь и подмешивается по slug. Для курса без своего лендинга страница
// собирается из данных Firestore (buildFallbackLanding) — витрина не ломается.

import { PROGRAM_URL, TELEGRAM_DM } from '@/lib/site';
import { nbspDeep } from '@/lib/typography';

export type Fact = { value: string; label: string };
// Ключи иконок для схемы цикла — рисуются через LandingIcon
export type IconKey = 'target' | 'book' | 'prompt' | 'diff' | 'shield' | 'eye' | 'commit';
// Логотипы инструментов и стеков — рисуются через BrandLogo
export type LogoKey =
  | 'claude' | 'codex' | 'kimi' | 'deepseek' | 'gemini'
  | 'js' | 'ts' | 'php' | 'python' | 'eslint' | 'vitest' | 'jest' | 'git' | 'github';
// logos — пара логотипов «колодой» в углу карточки, максимум две
export type Item = { title: string; note: string; logos?: readonly LogoKey[] };

export type CourseLanding = {
  eyebrow: string;
  // Обложка на витрине: перекрывает coverUrl из Firestore, когда есть свой рисунок
  cover?: string;
  h1: string;
  lead: string;
  // Плашка оффера в хиро: крупный маркер и пояснение
  offer: { badge: string; text: string } | null;
  facts: readonly Fact[];
  // Боли и запросы — «знакомо?» перед программой
  pains: readonly string[];
  // Что будет на выходе
  results: readonly Item[];
  // Что внутри: модули программы
  program: readonly Item[];
  // Кому подойдёт
  audience: readonly Item[];
  // Проверяемые прикладные сценарии: исходная рутина → работа агента → результат
  scenarios?: readonly { before: string; agent: string; after: string; control: string }[];
  // Понятные примеры проектов, которые можно собрать из навыков курса
  examples?: readonly Item[];
  // Честная квалификация до покупки
  requirements?: readonly { label: string; value: string }[];
  // Почему мы, а не курс-конвейер
  why: readonly Item[];
  // Формат работы
  format: readonly Item[];
  // Условия участия рядом с программой: нагрузка, сроки, домашки, подписки
  terms?: readonly { label: string; value: string }[];
  // Один проверяемый цикл работы вместо голых цифр — рисуется схемой-конвейером.
  // repoUrl — публичный демо-репозиторий, пока его нет, ссылка не рендерится
  caseStudy?: {
    title: string;
    source: string;
    repoUrl?: string;
    // шаги конвейера: короткая подпись для схемы и одна строка пояснения
    steps: readonly { icon: IconKey; label: string; short: string; detail: string }[];
    diff: { files: number; added: number; removed: number };
    checks: readonly string[];
    // время цикла: метки соседних коммитов
    from: string;
    to: string;
    minutes: string;
  };
  price: { value: string; note: string; includes: readonly string[] };
  // hint — мелкая подпись под кнопкой; без неё строка не рендерится
  cta: { label: string; href: string; hint?: string };
  seoTitle: string;
  seoDescription: string;
};

