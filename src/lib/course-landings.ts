export function getCourseLanding(slug: string): CourseLanding | null {
  const landing = LANDINGS[slug];
  // неразрывные пробелы расставляем на выходе — в тексте выше они не мешают читать
  return landing ? nbspDeep(landing) : null;
}

// Лендинг для курса без редакторского текста: честно собираем из данных Firestore.
// Продающих блоков нет — только то, что реально известно про курс.
export function buildFallbackLanding(course: {
  title: string;
  description: string;
  isTest: boolean;
}, lessons: readonly { title: string; description: string }[]): CourseLanding {
  return nbspDeep({
    eyebrow: 'обучение',
    h1: course.title,
    lead: course.description || 'Программа готовится. Напишите в личку — расскажем детали и позовём на старт.',
    offer: null,
    facts: [{ value: String(lessons.length), label: 'уроков в программе' }],
    pains: [],
    results: [],
    program: lessons.map((l) => ({ title: l.title, note: l.description })),
    audience: [],
    why: [],
    format: [],
    price: {
      value: course.isTest ? 'Открывается скоро' : 'Форматы участия',
      note: 'Формат и детали — в личке.',
      includes: [],
    },
    cta: { label: 'Написать в телеграм', href: TELEGRAM_DM, hint: 'Ответим лично, без рассылок.' },
    seoTitle: `${course.title} — обучение Gelato`,
    seoDescription: course.description || `Обучение «${course.title}» в школе Gelato.`,
  });
}
