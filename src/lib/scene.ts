/** Точка удара, на которую нарисован бросок — для расчёта buttonOffset по факту. */
export const HIT_IMPACT_POINT = { x: HIT_STOPS[HIT_STOPS.length - 1].x, y: HIT_STOPS[HIT_STOPS.length - 1].y };

export type HitPoint = { x: number; y: number; rot: number; opacity: number };

const clamp01 = (v: number) => Math.min(1, Math.max(0, v));

/** Плавная рампа 0→1 между двумя значениями t (кубическая, без рывка на границах). */
function smoothstep(edge0: number, edge1: number, x: number): number {
  const t = clamp01((x - edge0) / (edge1 - edge0));
  return t * t * (3 - 2 * t);
}

// Точки посадки на борт (t≈0.24–0.34) и удара в кнопку (t≈0.72–1) в HIT_STOPS
// подобраны на глаз по канве — кораблик и правда стоит примерно там, но живёт
// своей жизнью (скроллится translateX), а кнопка ещё и не имеет фиксированных
// размеров (текст, отступы). boatOffsetPx/buttonOffsetPx — поправка к этим
// точкам до фактического, посчитанного на этот кадр положения кораблика и
// кнопки в DOM; веса вводят её плавно ровно в диапазоне контакта, чтобы не
// сдвигать остальную часть дуги, которая была подобрана художественно.
const ON_BOAT_IN = [0.12, 0.24] as const;
const ON_BOAT_OUT = [0.34, 0.5] as const;
const TO_BUTTON = [0.72, 1] as const;

/**
 * @param rotOffset — вращение, на котором остановился катящийся лимон в конце
 * ROLL (см. rollRotationEnd): без него угол в момент прыжка сбрасывался бы
 * на 0 и лимон визуально «дёргался» в исходное положение вместо того, чтобы
 * продолжить вращение одним гладким движением.
 * @param boatOffsetX — насколько кораблик сейчас сдвинут скроллом от точки,
 * на которую нарисована посадка (см. rollRotationEnd про ту же идею).
 * @param buttonOffset — насколько измеренный центр кнопки в DOM отличается
 * от точки удара, на которую нарисован бросок.
 */
export function sampleHit(
  tRaw: number,
  rotOffset = 0,
  boatOffsetX = 0,
  buttonOffset: { x: number; y: number } = { x: 0, y: 0 },
): HitPoint {
  const t = Math.min(1, Math.max(0, tRaw));
  let i = 1;
  while (i < HIT_STOPS.length - 1 && HIT_STOPS[i].t < t) i++;
  const a = HIT_STOPS[i - 1];
  const b = HIT_STOPS[i];
  const span = b.t - a.t || 1;
  const k = EASE[b.ease](Math.min(1, Math.max(0, (t - a.t) / span)));
  const lerp = (x0: number, x1: number) => x0 + (x1 - x0) * k;

  const boatWeight = smoothstep(...ON_BOAT_IN, t) * (1 - smoothstep(...ON_BOAT_OUT, t));
  const buttonWeight = smoothstep(...TO_BUTTON, t);

  // до начала прыжка (там ещё катится обычный лимон) лимон-«снаряд» не
  // рисуется вовсе; в конце — не тает, а чётко разбивается об кнопку ровно
  // в момент удара, одним кадром вместе со вспышкой заливки
  const opacity = tRaw <= 0 || tRaw >= 1 ? 0 : 1;
  return {
    x: lerp(a.x, b.x) + boatWeight * boatOffsetX + buttonWeight * buttonOffset.x,
    y: lerp(a.y, b.y) + buttonWeight * buttonOffset.y,
    rot: lerp(a.rot, b.rot) + rotOffset,
    opacity,
  };
}

/** Угол, на котором катящийся лимон останавливается в конце ROLL (см. samplePath). */
export function rollRotationEnd(acc: readonly number[], radius = 34): number {
  return (acc[acc.length - 1] / radius) * (180 / Math.PI);
}
