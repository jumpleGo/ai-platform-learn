// Убирает у текста последний законченный фрагмент: сначала строку, потом
// предложение. Обрезаем только по знаку конца фразы — на полуслове не рвём.
export function dropTail(text: string): string | null {
  const trimmed = text.replace(/[\s\u00a0]+$/, '');
  const lines = trimmed.split('\n');
  if (lines.length > 1) {
    lines.pop();
    return lines.join('\n').replace(/[\s\u00a0]+$/, '');
  }
  const sentences = trimmed.split(/(?<=[.!?…])[\s\u00a0]+/);
  if (sentences.length > 1) {
    sentences.pop();
    return sentences.join(' ');
  }
  return null;
}

// ── Ломаная: выборка точки по доле пути ──────────────────────────────────────

export type RollPoint = { x: number; y: number; rot: number };

/** Длины сегментов и общая длина ломаной — считаются один раз. */
export function measure(line: readonly (readonly [number, number])[]) {
  const acc = [0];
  for (let i = 1; i < line.length; i++) {
    const [x0, y0] = line[i - 1];
    const [x1, y1] = line[i];
    acc.push(acc[i - 1] + Math.hypot(x1 - x0, y1 - y0));
  }
  return acc;
}

/**
 * Точка на ломаной по доле пройденного пути (0..1) плюс угол поворота лимона:
 * он катится, поэтому угол — это длина пути, поделённая на радиус.
 */
export function samplePath(
  line: readonly (readonly [number, number])[],
  acc: readonly number[],
  t: number,
  // радиус катящегося лимона: половина его тела, без листка
  radius = 34,
): RollPoint {
  const total = acc[acc.length - 1];
  const target = Math.min(1, Math.max(0, t)) * total;
  let i = 1;
  while (i < acc.length - 1 && acc[i] < target) i++;
  const span = acc[i] - acc[i - 1] || 1;
  const k = (target - acc[i - 1]) / span;
  const [x0, y0] = line[i - 1];
  const [x1, y1] = line[i];
  return {
    x: x0 + (x1 - x0) * k,
    y: y0 + (y1 - y0) * k,
    rot: (target / radius) * (180 / Math.PI),
  };
}
